#!/usr/bin/env bash
# Lift keyreg/keys.rs (the ira and wairua held in CPU registers, safe Rust) to keyreg/keys.s, the assembly the kernel links (KEY_REGISTERS.md, derive -> audit -> freeze).
#
# The Rust is compiled with the kernel's own codegen flags (.cargo/config.toml) at -O2 (at -O3 LLVM unrolls the seven rounds, runs out of vector registers and saves v8-v15 on the stack; -O2 keeps the round loop rolled: 2026-10-28), then the output is refused if any function touches the stack or calls out: no `sp` operand at all (no frame, no spill, no saved register), no `bl`/`blr`/`b` to a symbol outside the file. A secret in a register that LLVM spilled would sit in DRAM, which is the one thing this exists to prevent.
#
# Usage:
#   tools/keyreg-lift.sh           regenerate keyreg/keys.s and check it
#   tools/keyreg-lift.sh --check   check that keyreg/keys.s is what the current toolchain makes of keys.rs (CI: no drift, no spill)
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$REPO/keyreg/keys.rs"
OUT="$REPO/keyreg/keys.s"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FEATURES="$(sed -n 's/^rustflags = \["-C", "target-feature=\([^"]*\)"\]/\1/p' "$REPO/.cargo/config.toml" | head -1)"
[ -n "$FEATURES" ] || { echo "keyreg-lift: no target-feature line in .cargo/config.toml" >&2; exit 1; }

rustc --edition 2024 --crate-type lib --target aarch64-unknown-none -C opt-level=2 -C panic=abort -C target-feature="$FEATURES" --emit asm -o "$TMP/raw.s" "$SRC"

{
    echo "// GENERATED by tools/keyreg-lift.sh from keyreg/keys.rs — do not edit; edit keys.rs and lift again."
    echo "// $(rustc --version)"
    grep -vE '^\s*\.(file|ident|addrsig|addrsig_sym)\b' "$TMP/raw.s"
    # Scrub: the caller-saved registers a key function may have left secrets in. Hand-written, the one addition to what the compiler made.
    cat <<'EOF'
	.section	.text.keyreg_scrub,"ax",@progbits
	.globl	keyreg_scrub
	.p2align	2
	.type	keyreg_scrub,@function
keyreg_scrub:
	movi	v0.2d, #0
	movi	v1.2d, #0
	movi	v2.2d, #0
	movi	v3.2d, #0
	movi	v4.2d, #0
	movi	v5.2d, #0
	movi	v6.2d, #0
	movi	v7.2d, #0
	movi	v16.2d, #0
	movi	v17.2d, #0
	movi	v18.2d, #0
	movi	v19.2d, #0
	movi	v20.2d, #0
	movi	v21.2d, #0
	movi	v22.2d, #0
	movi	v23.2d, #0
	movi	v24.2d, #0
	movi	v25.2d, #0
	movi	v26.2d, #0
	movi	v27.2d, #0
	movi	v28.2d, #0
	movi	v29.2d, #0
	movi	v30.2d, #0
	movi	v31.2d, #0
	mov	x0, xzr
	mov	x1, xzr
	mov	x2, xzr
	mov	x3, xzr
	mov	x4, xzr
	mov	x5, xzr
	mov	x6, xzr
	mov	x7, xzr
	mov	x8, xzr
	mov	x9, xzr
	mov	x10, xzr
	mov	x11, xzr
	mov	x12, xzr
	mov	x13, xzr
	mov	x14, xzr
	mov	x15, xzr
	mov	x16, xzr
	mov	x17, xzr
	ret
.Lfunc_end_keyreg_scrub:
	.size	keyreg_scrub, .Lfunc_end_keyreg_scrub-keyreg_scrub
EOF
} > "$TMP/keys.s"

fail=0
# Any instruction naming sp: a frame, a spill, a saved callee register.
if grep -nE '^\s+[a-z0-9.]+\s.*\bsp\b' "$TMP/keys.s" | grep -vE '^\s*//' ; then echo "keyreg-lift: REFUSED — the code above touches the stack" >&2; fail=1; fi
# Callee-saved vector registers (v8-v15, d8-d15): using them would mean saving them, on the stack.
if grep -nE '\b[vdq](8|9|1[0-5])\b' "$TMP/keys.s"; then echo "keyreg-lift: REFUSED — callee-saved vector registers used" >&2; fail=1; fi
# Calls out of the file (memcpy, a panic): each would be code nobody audited, running with a secret live.
if grep -nE '^\s+(bl|blr|br)\s' "$TMP/keys.s"; then echo "keyreg-lift: REFUSED — a call out" >&2; fail=1; fi
if grep -nE '^\s+b\s+[A-Za-z_]' "$TMP/keys.s" | grep -vE '\s\.L'; then echo "keyreg-lift: REFUSED — a tail call out" >&2; fail=1; fi
[ $fail -eq 0 ] || exit 1

if [ "${1:-}" = "--check" ]; then
    diff -u "$OUT" "$TMP/keys.s" && echo "keyreg-lift: keys.s matches keys.rs, no stack, no calls out"
    exit $?
fi
cp "$TMP/keys.s" "$OUT"
echo "keyreg-lift: wrote keyreg/keys.s ($(grep -cE '^\s+[a-z]' "$OUT") instructions), no stack, no calls out"
