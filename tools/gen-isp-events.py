#!/usr/bin/env python3
"""Generate ferros_kernel/src/camera_events.rs from the LWIS ISP event tables in the Pixel kernel tree.

`zuma-isp-event-info.dtsi` names every interrupt source, mask, overflow and reset register of every block in the ISP, and `dt-bindings/lwis/platform/zuma/*.h` names every bit in them. LWIS's own logic is a passthrough, but its device tree carries the register semantics the proprietary HAL otherwise keeps to itself — so this is the ISP front end's register map, and it is open source.

What it buys: ferros can read every event source in the pipeline and print the set bits by name, instead of diffing opaque words. The first use found that ferros's front end only ever raises SHADOW_UPDATE and never SOF, which is what moved the camera's open question from "the frame writer is idle" to "no frame ever enters the front end".

Usage: tools/gen-isp-events.py [reference tree] > ferros_kernel/src/camera_events.rs
"""
import re, sys, glob, os

REF = sys.argv[1] if len(sys.argv) > 1 else "/mnt/Harbor/ferros-ref"
DTSI = f"{REF}/kdev-zuma/dts/zuma-isp-event-info.dtsi"
HDRS = glob.glob(f"{REF}/soc-gs/include/dt-bindings/lwis/platform/zuma/*.h") + \
       glob.glob(f"{REF}/soc-gs/include/dt-bindings/lwis/platform/*.h")

# bit macro -> bit number
bits = {}
for h in HDRS:
    for l in open(h):
        m = re.match(r'#define\s+([A-Z0-9_]+)\s+(\d+)\s*$', l)
        if m:
            bits[m.group(1)] = int(m.group(2))

# the register spaces we can address, from lwis_isp_fe's reg/reg-names in zuma-isp.dtsi
SPACES = {
    "isp-fe": 0x1C30_0000,
    "csis-link-phy": 0x1C04_0000,
    "isp-fe-sysreg": 0x1C02_0000,
    "pdma": 0x1C39_0000,
    "pdma-wrap": 0x1C39_5000,
}

text = open(DTSI).read()
nodes = []
for m in re.finditer(r'(\w+):\s*[\w-]+-event-info@[0-9a-fx]+\s*\{(.*?)\n\t\};', text, re.S):
    name, body = m.group(1), m.group(2)
    sp = re.search(r'irq-reg-space\s*=\s*"([^"]+)"', body)
    src = re.search(r'irq-src-reg\s*=\s*<([^>]+)>', body)
    if not sp or not src or sp.group(1) not in SPACES:
        continue
    cells = src.group(1).split()
    off = int(cells[-1], 16)
    mask = re.search(r'irq-mask-reg\s*=\s*<([^>]+)>', body)
    moff = int(mask.group(1).split()[-1], 16) if mask else 0
    kind = re.search(r'irq-type\s*=\s*"([^"]+)"', body)
    macros = re.findall(r'<\s*(ISP_FE_[A-Z0-9_]+|[A-Z][A-Z0-9_]*)\s*>', body.split('int-reg-bits')[-1]) if 'int-reg-bits' in body else []
    ev = []
    for mac in macros:
        if mac in bits:
            short = mac
            # drop the longest prefix the node name already carries
            up = name.upper()
            for cut in range(len(up), 4, -1):
                if mac.startswith(up[:cut]):
                    short = mac[cut:].lstrip('_') or mac
                    break
            ev.append((bits[mac], short))
    nodes.append((sp.group(1), off, moff, name, kind.group(1) if kind else "", ev))

print("//! The ISP pipeline's interrupt sources, every one named, generated by tools/gen-isp-events.py from the Pixel kernel's LWIS event tables.")
print("//!")
print("//! Do not edit by hand. `zuma-isp-event-info.dtsi` plus `dt-bindings/lwis/platform/zuma/*.h` name every event register and every bit in it; LWIS is only a passthrough, but its device tree is where the ISP front end's register semantics are written down in the open.")
print("//! Reading these and printing the set bits by name is what turns register archaeology into a reading of the pipeline: which stage is alive, and where it goes quiet.")
print()
print("/// A block's register base, as `lwis_isp_fe`'s `reg`/`reg-names` pair them.")
print("pub const SPACES: [(&str, usize); %d] = [" % len(SPACES))
for k, v in SPACES.items():
    print(f'    ("{k}", 0x{v:08X}),')
print("];")
print()
print("/// One interrupt source: its space base, offset, mask-register offset (0 when it has none), node name, kind, and the name of each bit.")
print("pub struct Source {")
print("    pub base: usize,")
print("    pub off: usize,")
print("    pub mask_off: usize,")
print("    pub name: &'static str,")
print("    pub kind: &'static str,")
print("    pub bits: &'static [(u8, &'static str)],")
print("}")
print()
print(f"pub const SOURCES: [Source; {len(nodes)}] = [")
for sp, off, moff, name, kind, ev in nodes:
    b = ", ".join(f'({n}, "{s}")' for n, s in ev)
    print(f'    Source {{ base: 0x{SPACES[sp]:08X}, off: 0x{off:X}, mask_off: 0x{moff:X}, name: "{name}", kind: "{kind}", bits: &[{b}] }},')
print("];")
