#!/usr/bin/env python3
"""The registers a live-state snapshot of the camera receive path reads: only addresses known to exist, so a snapshot taken mid-stream (by the hv under Linux, or by ferros cold) cannot wander into a hole and stall the bus.

Sources, unioned:
  - every CMU_TOP and CMU_ISPFE register cmucal-sfr.c names (the Pixel kernel's clock tables);
  - every address the ISP front-end capture saw the CPU read or write (target/hv/ispfe-full-raw.log);
  - every register the PDMA program writes (docs/oracle/camera-ispfe-pdma-writes.txt), minus the block-load region at G#1C36_xxxx;
  - every interrupt status and mask register the LWIS event tables name (ferros_kernel/src/camera_events.rs);
  - CSI links 0 and 1, words G#000..G#1FC and G#600..G#6FC.

Writes one hex address per line, sorted, to stdout. Usage: tools/camera-snap-list.py > target/hv/snap-list.txt
With `--rust <hv log>` it instead turns an hv snapshot (`SN addr value` lines, FERROS_HV_SNAPSHOT) into ferros_kernel/src/camera_snap.rs, Linux's values for ferros to compare against.
"""
import sys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CMUCAL = Path("/mnt/Harbor/ferros-ref/soc-gs/drivers/soc/google/cal-if/zuma/cmucal-sfr.c")

if len(sys.argv) == 3 and sys.argv[1] == "--rust":
    pairs = []
    for line in Path(sys.argv[2]).read_text(errors="replace").splitlines():
        m = re.search(r"ferros hv: SN ([0-9A-F]{16}) ([0-9A-F]{16})", line)
        if m:
            pairs.append((int(m[1], 16), int(m[2], 16)))
    out = ["//! Linux's live camera receive-path registers, read by the hv sixteen frames into a stream (FERROS_HV_SNAPSHOT, 2026-10-21): what `diag cam pdma` compares a cold ferros against.", "//!", "//! Generated by `tools/camera-snap-list.py --rust`; do not edit by hand.", "", f"pub const LINUX_SNAP: [(u32, u32); {len(pairs)}] = ["]
    out += [f"    ({a:#X}, {v:#X})," for a, v in pairs]
    out.append("];")
    (ROOT / "ferros_kernel/src/camera_snap.rs").write_text("\n".join(out).replace("0X", "0x") + "\n")
    print(f"{len(pairs)} registers")
    sys.exit(0)

addrs = set()
src = CMUCAL.read_text()
blocks = {m[1]: int(m[2], 16) for m in re.finditer(r"SFR_BLOCK\((\w+),\s*0x([0-9a-fA-F]+),", src)}
for m in re.finditer(r"SFR\(\w+,\s*0x([0-9a-fA-F]+),\s*(CMU_TOP|CMU_ISPFE)\)", src):
    addrs.add(blocks[m[2]] + int(m[1], 16))
for line in (ROOT / "target/hv/ispfe-full-raw.log").read_text(errors="replace").splitlines():
    m = re.search(r"S2 ([0-9A-F]{16}) [RW]", line)
    if m:
        addrs.add(int(m[1], 16))
for line in (ROOT / "docs/oracle/camera-ispfe-pdma-writes.txt").read_text().splitlines():
    m = re.match(r"W G#([0-9A-F]+) =", line)
    if m:
        a = int(m[1], 16)
        if a & ~0xFFFF != 0x1C36_0000:
            addrs.add(a)
for m in re.finditer(r"base: 0x([0-9A-F]+), off: 0x([0-9A-F]+), mask_off: 0x([0-9A-F]+)", (ROOT / "ferros_kernel/src/camera_events.rs").read_text()):
    b = int(m[1], 16)
    addrs.update({b + int(m[2], 16), b + int(m[3], 16)})
for link in (0x1C04_0000, 0x1C05_0000):
    addrs.update(link + o for o in list(range(0, 0x200, 4)) + list(range(0x600, 0x700, 4)))
addrs = sorted(a & ~3 for a in addrs)
for a in sorted(set(addrs)):
    print(f"{a:X}")
