pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "ऊँचाई {up}°, दिशा {round}°, {cn0} dB-Hz{}", if used { ", फ़िक्स में" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("चिप से संदेश: ")?;
            num(o, f, messages)?;
            o.write_str(", प्रकार: ")?;
            num(o, f, kinds)?;
            o.write_str("; उपग्रह पहली स्थिति के साथ आते हैं")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, गर्मियों का समय"),
        Say::HeardMcc(mcc) => write!(o, "सुना: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "सुना: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            // टैप does not change with the count.
            o.write_str("डेवलपर तक ")?;
            num(o, f, n)?;
            o.write_str(" टैप बाक़ी")
        }
        Say::Charging(pct) => write!(o, "{pct}  चार्ज हो रहा है"),
        Say::OnBattery(pct) => write!(o, "{pct}  बैटरी पर"),
        Say::ChargeCapAt { mv, share } => write!(o, "{mv}, लगभग {share}"),
        Say::ChargeCapDefault(mv) => write!(o, "{mv} डिफ़ॉल्ट है: लगभग पूरा चार्ज, बहुत कम घिसाव के साथ।"),
        Say::ApproveChargeCap(mv) => write!(o, "मंज़ूर करो: {mv} तक चार्ज करें।"),
        Say::ChargeCapCycles { share, mv } => write!(o, "{mv} पर लगभग {share} चार्ज चक्र"),
        Say::Throttled(t) => write!(o, "{t}  धीमा किया गया"),
        Say::NotAskedYet(what) => write!(o, "{what} (अभी पूछा नहीं)"),
        Say::UsingNow(what) => write!(o, "{what} (अभी इस्तेमाल में)"),
        Say::CouldNotStart(name) => write!(o, "{name} शुरू नहीं हो सका"),
        Say::Stopped(name) => write!(o, "{name} रुक गया"),
        Say::ByDeveloper(name) => write!(o, "{name} का"),
        Say::KeptForItself(size) => write!(o, "{size}, इसके बिना बेकार"),
        Say::Fetching { name, got } => write!(o, "{name} लाया जा रहा है: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "{name} लाया जा रहा है: {total} में से {got}"),
        Say::Signal(dbm) => write!(o, "सिग्नल {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "{name} से जुड़ रहे हैं।"),
        Say::PassphraseFor(name) => write!(o, "{name} का पासवर्ड।"),
        Say::OutOfReach(name) => write!(o, "{name} पहुँच से बाहर है।"),
        Say::SecurityUnsupported(name) => write!(o, "{name} को ऐसी सुरक्षा चाहिए जिससे यह डिवाइस अभी नहीं जुड़ सकता।"),
        Say::DidNotAnswer(name) => write!(o, "{name} ने जवाब नहीं दिया। फिर कोशिश करो।"),
        Say::RefusedPassphrase(name) => write!(o, "{name} ने पासवर्ड ठुकरा दिया।"),
        Say::TypeOnKeyboard(name) => write!(o, "{name} का पासवर्ड कीबोर्ड पर लिखो।"),
        Say::JoinedNet(name) => write!(o, "{name} से जुड़ गए।"),
        Say::Forgotten(name) => write!(o, "{name} भुला दिया गया।"),
        Say::OpenIn(name) => write!(o, "{name} में खोलो"),
        Say::PassphraseLength { min, max } => {
            o.write_str("पासवर्ड ")?;
            num(o, f, min)?;
            o.write_str(" से ")?;
            num(o, f, max)?;
            o.write_str(" सादे अक्षरों का होता है।")
        }
        Say::UnderFullScale(n) => {
            o.write_str("पूर्ण स्तर से ")?;
            num(o, f, n)?;
            o.write_str(" dB नीचे")?;
            Ok(())
        }
        Say::AmpState { side, pup, pll, errors } => {
            o.write_str(side)?;
            o.write_str(": PUP_DONE ")?;
            num(o, f, pup)?;
            o.write_str(", PLL लॉक ")?;
            num(o, f, pll)?;
            o.write_str(", त्रुटियाँ ")?;
            o.write_str(errors)?;
            Ok(())
        }
        Say::MicLevel { mic, under } => {
            o.write_str("माइक्रोफ़ोन ")?;
            num(o, f, mic)?;
            o.write_str(": पूर्ण स्तर से ")?;
            num(o, f, under)?;
            o.write_str(" dB नीचे")?;
            Ok(())
        }
        Say::MicQuiet(mic) => {
            o.write_str("माइक्रोफ़ोन ")?;
            num(o, f, mic)?;
            o.write_str(": ख़ामोश")?;
            Ok(())
        }
        Say::MicName(n) => {
            o.write_str("माइक्रोफ़ोन ")?;
            num(o, f, n)?;
            Ok(())
        }
        Say::PlayingBack(d) => {
            o.write_str("रिकॉर्ड हुआ, शिखर पूर्ण स्तर से ")?;
            num(o, f, d)?;
            o.write_str(" dB नीचे: वापस चल रहा है")?;
            Ok(())
        }
        Say::RomWaveform(n) => {
            o.write_str("ROM तरंग-रूप ")?;
            num(o, f, n)?;
            Ok(())
        }
    }
}
