//! The glass console's cells for tatau's numbers (2026-11-22, owner: "We need console glyphs for dozenal"): the twelve dozenal digits (U+0010-U+001B), the radix point (U+00B7) and the sign arrows (U+2191, U+2193), rasterised at build time from Oxanium Regular +glyphs (assets/fonts), the face and the rasteriser the kernel's text atlas uses (kernel/build.rs `text_atlas`), into the 8x16 bitmap font's grid.
//!
//! - **Size:** the size at which Oxanium's capital height is the bitmap font's, 10 rows (rows 2 to 11), sitting on its baseline (row 12), so a dozenal number lines up with the ASCII beside it.
//! - **Width:** a dozenal digit is about an em wide (Oxanium's ASCII digits about 0.6), so each takes two cells, 16 pixels, as a terminal gives a wide character two; the point and the arrows take one.
//! - **Bits:** the glass paints spans, one colour a cell pixel, so the coverage is cut at half: a pixel at least half covered is lit; then each lit pixel lights its right neighbour too, to the bitmap font's two-pixel stems.
//! - **Out:** `dozenal.rs` in OUT_DIR, the cells as the bitmap font holds them (16 bytes, one a scanline, the most significant bit leftmost): digit d's left half at 2d, its right half at 2d + 1, then the point, the up arrow, the down arrow.
//!   A glyph that does not fit its cells fails the build.

const GLYPH_W: usize = 8;
const GLYPH_H: usize = 16;
/// The bitmap font's capital height in rows ('H' and '8' fill rows 2 to 11).
const CAP: f32 = 10.;
/// The row just below the bitmap font's baseline.
const BASELINE: i32 = 12;

fn main() {
    let font_path = format!("{}/../../assets/fonts/Oxanium-Regular+glyphs.ttf", std::env::var("CARGO_MANIFEST_DIR").unwrap());
    println!("cargo:rerun-if-changed={font_path}");
    println!("cargo:rerun-if-changed=build.rs");
    let bytes = std::fs::read(&font_path).expect("Oxanium-Regular+glyphs.ttf");
    let font = fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default()).expect("font");
    let probe = font.metrics('H', 100.);
    let px = 100. * CAP / probe.bounds.height;
    // (character, cells wide)
    let chars: Vec<(char, usize)> = (0x10u32..0x1C).map(|c| (char::from_u32(c).unwrap(), 2)).chain([('\u{B7}', 1), ('\u{2191}', 1), ('\u{2193}', 1)]).collect();
    let mut out = String::from("// Generated by crates/glass/build.rs from assets/fonts/Oxanium-Regular+glyphs.ttf: the dozenal digits' halves, the radix point and the sign arrows.\n#[rustfmt::skip]\npub static EXTRA: [[u8; 16]; 27] = [\n");
    for (c, cells) in chars {
        let (m, cover) = font.rasterize(c, px);
        let w = GLYPH_W * cells;
        // The advance centred in the cells, the glyph placed from the pen by its own offsets.
        let pen = (w as i32 - m.advance_width.round() as i32) / 2;
        let x0 = pen + m.xmin;
        let y0 = BASELINE - m.ymin - m.height as i32;
        let mut rows = [0u32; GLYPH_H];
        for gy in 0..m.height {
            for gx in 0..m.width {
                if cover[gy * m.width + gx] < 128 {
                    continue;
                }
                let (x, y) = (x0 + gx as i32, y0 + gy as i32);
                assert!(x >= 0 && (x as usize) < w && y >= 0 && (y as usize) < GLYPH_H, "U+{:04X} at {px} px reaches ({x}, {y}), outside its {w}x{GLYPH_H} cells", c as u32);
                rows[y as usize] |= 1 << (w - 1 - x as usize);
            }
        }
        // Emboldened one pixel to the right: the bitmap font's stems are two pixels wide, Oxanium's at this size one.
        for r in rows.iter_mut() {
            *r |= *r >> 1;
        }
        for half in (0..cells).rev() {
            let bytes: Vec<String> = rows.iter().map(|r| format!("0x{:02X}", (r >> (8 * half)) & 0xFF)).collect();
            out.push_str(&format!("    // U+{:04X}{}\n    [{}],\n", c as u32, if cells == 2 { if half == 1 { " left" } else { " right" } } else { "" }, bytes.join(",")));
        }
    }
    out.push_str("];\n");
    std::fs::write(std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("dozenal.rs"), out).unwrap();
}
