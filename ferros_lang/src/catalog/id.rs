pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° tinggi, {round}° arah, {cn0} dB-Hz{}", if used { ", dipakai untuk posisi" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("pesan dari cip: ")?;
            num(o, f, messages)?;
            o.write_str(", jenis: ")?;
            num(o, f, kinds)?;
            o.write_str("; satelit muncul bersama posisi pertamanya")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, waktu musim panas"),
        Say::HeardMcc(mcc) => write!(o, "terdengar: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "terdengar: MCC {mcc}, {country}"),
        // Indonesian does not mark the plural after a number; one form serves every count.
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(" ketukan lagi menuju Pengembang")
        }
        Say::Charging(pct) => write!(o, "{pct}  mengisi daya"),
        Say::OnBattery(pct) => write!(o, "{pct}  pakai baterai"),
        Say::Throttled(t) => write!(o, "{t}  diperlambat"),
        Say::NotAskedYet(what) => write!(o, "{what} (belum ditanyakan)"),
        Say::UsingNow(what) => write!(o, "{what} (sedang dipakai)"),
        Say::CouldNotStart(name) => write!(o, "{name} tidak dapat dimulai"),
        Say::Signal(dbm) => write!(o, "Sinyal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Bergabung ke {name}."),
        Say::PassphraseFor(name) => write!(o, "Frasa sandi untuk {name}."),
        Say::OutOfReach(name) => write!(o, "{name} di luar jangkauan."),
        Say::SecurityUnsupported(name) => write!(o, "{name} memerlukan jenis keamanan yang belum bisa dimasuki perangkat ini."),
        Say::DidNotAnswer(name) => write!(o, "{name} tidak menjawab. Coba lagi."),
        Say::RefusedPassphrase(name) => write!(o, "{name} menolak frasa sandinya."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Frasa sandi terdiri dari ")?;
            num(o, f, min)?;
            o.write_str(" sampai ")?;
            num(o, f, max)?;
            o.write_str(" karakter biasa.")
        }
    }
}
