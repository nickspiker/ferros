pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° de elevación, {round}° de acimut, {cn0} dB-Hz{}", if used { ", en uso" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("mensajes del chip: ")?;
            num(o, f, messages)?;
            o.write_str(", tipos: ")?;
            num(o, f, kinds)?;
            o.write_str("; los satélites llegan con su primera posición")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, horario de verano"),
        Say::HeardMcc(mcc) => write!(o, "recibido: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "recibido: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " toque para Desarrollador" } else { " toques para Desarrollador" })
        }
        Say::Charging(pct) => write!(o, "{pct}  cargando"),
        Say::OnBattery(pct) => write!(o, "{pct}  con batería"),
        Say::Throttled(t) => write!(o, "{t}  limitado"),
        Say::NotAskedYet(what) => write!(o, "{what} (aún no preguntado)"),
        Say::UsingNow(what) => write!(o, "{what} (en uso ahora)"),
        Say::CouldNotStart(name) => write!(o, "{name} no pudo iniciarse"),
        Say::Stopped(name) => write!(o, "{name} se detuvo"),
        Say::Signal(dbm) => write!(o, "Señal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Conectando a {name}."),
        Say::PassphraseFor(name) => write!(o, "La contraseña de {name}."),
        Say::OutOfReach(name) => write!(o, "{name} está fuera de alcance."),
        Say::SecurityUnsupported(name) => write!(o, "{name} usa un tipo de seguridad con el que este dispositivo aún no puede conectarse."),
        Say::DidNotAnswer(name) => write!(o, "{name} no respondió. Inténtalo de nuevo."),
        Say::RefusedPassphrase(name) => write!(o, "{name} rechazó la contraseña."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Una contraseña tiene de ")?;
            num(o, f, min)?;
            o.write_str(" a ")?;
            num(o, f, max)?;
            o.write_str(" caracteres simples.")
        }
    }
}
