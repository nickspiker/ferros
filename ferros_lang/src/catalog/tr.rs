pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        // As in Photon's tr.rs, no suffix is glued to an inserted name (its last vowel is unknown when this is compiled): each sentence keeps the name bare.
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° yükseklik, {round}° azimut, {cn0} dB-Hz{}", if used { ", konumda" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("çipten gelen mesajlar: ")?;
            num(o, f, messages)?;
            o.write_str(", tür: ")?;
            num(o, f, kinds)?;
            o.write_str("; uydular ilk konumla gelir")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, yaz saati"),
        Say::HeardMcc(mcc) => write!(o, "duyulan: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "duyulan: MCC {mcc}, {country}"),
        // Turkish keeps the noun singular after a number, so one form serves every count.
        Say::TapsToDeveloper(n) => {
            o.write_str("Geliştirici sayfasına ")?;
            num(o, f, n)?;
            o.write_str(" dokunuş kaldı")
        }
        Say::Charging(pct) => write!(o, "{pct}  şarj oluyor"),
        Say::OnBattery(pct) => write!(o, "{pct}  pilde"),
        Say::Throttled(t) => write!(o, "{t}  kısıldı"),
        Say::NotAskedYet(what) => write!(o, "{what} (henüz sorulmadı)"),
        Say::UsingNow(what) => write!(o, "{what} (şu an kullanıyor)"),
        Say::CouldNotStart(name) => write!(o, "{name} başlatılamadı"),
        Say::Stopped(name) => write!(o, "{name} durdu"),
        Say::ByDeveloper(name) => write!(o, "{name} tarafından"),
        Say::KeptForItself(size) => write!(o, "{size}, o olmadan işe yaramaz"),
        Say::Fetching { name, got } => write!(o, "{name} alınıyor: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "{name} alınıyor: {got} / {total}"),
        Say::Signal(dbm) => write!(o, "Sinyal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "{name} ağına katılınıyor."),
        Say::PassphraseFor(name) => write!(o, "{name} ağının parolası."),
        Say::OutOfReach(name) => write!(o, "{name} menzil dışında."),
        Say::SecurityUnsupported(name) => write!(o, "{name}, bu cihazın henüz katılamadığı bir güvenlik türü istiyor."),
        Say::DidNotAnswer(name) => write!(o, "{name} yanıt vermedi. Tekrar dene."),
        Say::RefusedPassphrase(name) => write!(o, "{name} parolayı reddetti."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Parola ")?;
            num(o, f, min)?;
            o.write_str(" ile ")?;
            num(o, f, max)?;
            o.write_str(" arası basit karakterden oluşur.")
        }
    }
}
