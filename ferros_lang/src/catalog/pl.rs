/// The Polish count noun: 1 / 2-4 (not 12-14) / everything else.
fn pick<'s>(n: u64, one: &'s str, few: &'s str, many: &'s str) -> &'s str {
    if n == 1 {
        one
    } else if matches!(n % 10, 2..=4) && !matches!(n % 100, 12..=14) {
        few
    } else {
        many
    }
}

pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "wysokość {up}°, azymut {round}°, {cn0} dB-Hz{}", if used { ", użyty do pozycji" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("wiadomości z układu: ")?;
            num(o, f, messages)?;
            o.write_str(", rodzaje: ")?;
            num(o, f, kinds)?;
            o.write_str("; satelity pojawią się z pierwszą pozycją")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, czas letni"),
        Say::HeardMcc(mcc) => write!(o, "odebrano: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "odebrano: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(pick(n, " dotknięcie", " dotknięcia", " dotknięć"))?;
            o.write_str(" do strony Programista")
        }
        Say::Charging(pct) => write!(o, "{pct}  ładowanie"),
        Say::OnBattery(pct) => write!(o, "{pct}  na baterii"),
        Say::Throttled(t) => write!(o, "{t}  spowolniony"),
        Say::NotAskedYet(what) => write!(o, "{what} (jeszcze nie pytano)"),
        Say::UsingNow(what) => write!(o, "{what} (używa teraz)"),
        Say::CouldNotStart(name) => write!(o, "Nie udało się uruchomić {name}"),
        Say::Stopped(name) => write!(o, "Zatrzymano {name}"),
        Say::Signal(dbm) => write!(o, "Sygnał {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Łączenie z siecią {name}."),
        Say::PassphraseFor(name) => write!(o, "Hasło do sieci {name}."),
        Say::OutOfReach(name) => write!(o, "Sieć {name} jest poza zasięgiem."),
        Say::SecurityUnsupported(name) => write!(o, "Sieć {name} wymaga zabezpieczeń, z którymi to urządzenie nie umie jeszcze dołączyć."),
        Say::DidNotAnswer(name) => write!(o, "Sieć {name} nie odpowiedziała. Spróbuj ponownie."),
        Say::RefusedPassphrase(name) => write!(o, "Sieć {name} odrzuciła hasło."),
        Say::PassphraseLength { min, max } => {
            // After "od ... do" the noun is genitive: "znaków" for every count above one.
            o.write_str("Hasło ma od ")?;
            num(o, f, min)?;
            o.write_str(" do ")?;
            num(o, f, max)?;
            o.write_str(if max == 1 { " zwykłego znaku." } else { " zwykłych znaków." })
        }
    }
}
