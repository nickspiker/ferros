pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° Höhe, {round}° Azimut, {cn0} dB-Hz{}", if used { ", in der Position" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("Meldungen vom Chip: ")?;
            num(o, f, messages)?;
            o.write_str(", Arten: ")?;
            num(o, f, kinds)?;
            o.write_str("; Satelliten kommen mit der ersten Position")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, Sommerzeit"),
        Say::HeardMcc(mcc) => write!(o, "empfangen: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "empfangen: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            // "Mal" takes no plural: one form for every count.
            o.write_str(" Mal tippen bis Entwickler")
        }
        Say::Charging(pct) => write!(o, "{pct}  lädt"),
        Say::OnBattery(pct) => write!(o, "{pct}  im Akkubetrieb"),
        Say::Throttled(t) => write!(o, "{t}  gedrosselt"),
        Say::NotAskedYet(what) => write!(o, "{what} (noch nicht gefragt)"),
        Say::UsingNow(what) => write!(o, "{what} (nutzt es gerade)"),
        Say::CouldNotStart(name) => write!(o, "{name} konnte nicht starten"),
        Say::Stopped(name) => write!(o, "{name} wurde beendet"),
        Say::ByDeveloper(name) => write!(o, "von {name}"),
        Say::Signal(dbm) => write!(o, "Signal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Verbinde mit {name}."),
        Say::PassphraseFor(name) => write!(o, "Die Passphrase für {name}."),
        Say::OutOfReach(name) => write!(o, "{name} ist außer Reichweite."),
        Say::SecurityUnsupported(name) => write!(o, "{name} braucht eine Art von Sicherheit, mit der sich dieses Gerät noch nicht verbinden kann."),
        Say::DidNotAnswer(name) => write!(o, "{name} hat nicht geantwortet. Versuch es noch einmal."),
        Say::RefusedPassphrase(name) => write!(o, "{name} hat die Passphrase abgelehnt."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Eine Passphrase hat ")?;
            num(o, f, min)?;
            o.write_str(" bis ")?;
            num(o, f, max)?;
            o.write_str(" einfache Zeichen.")
        }
    }
}
