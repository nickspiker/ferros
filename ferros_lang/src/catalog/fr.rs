pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° d’élévation, {round}° d’azimut, {cn0} dB-Hz{}", if used { ", utilisé pour la position" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("messages de la puce : ")?;
            num(o, f, messages)?;
            o.write_str(", types : ")?;
            num(o, f, kinds)?;
            o.write_str(" ; les satellites arrivent avec sa première position")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, heure d’été"),
        Say::HeardMcc(mcc) => write!(o, "capté : MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "capté : MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            // French takes the singular for zero and one.
            o.write_str(if n < 2 { " appui jusqu’à Développeur" } else { " appuis jusqu’à Développeur" })
        }
        Say::Charging(pct) => write!(o, "{pct}  en charge"),
        Say::OnBattery(pct) => write!(o, "{pct}  sur batterie"),
        Say::Throttled(t) => write!(o, "{t}  bridée"),
        Say::NotAskedYet(what) => write!(o, "{what} (pas encore demandé)"),
        Say::UsingNow(what) => write!(o, "{what} (l’utilise maintenant)"),
        Say::CouldNotStart(name) => write!(o, "{name} n’a pas pu démarrer"),
        Say::Stopped(name) => write!(o, "{name} s’est arrêté"),
        Say::ByDeveloper(name) => write!(o, "par {name}"),
        Say::Signal(dbm) => write!(o, "Signal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Connexion à {name}."),
        Say::PassphraseFor(name) => write!(o, "La phrase secrète pour {name}."),
        Say::OutOfReach(name) => write!(o, "{name} est hors de portée."),
        Say::SecurityUnsupported(name) => write!(o, "{name} exige un type de sécurité que cet appareil ne sait pas encore rejoindre."),
        Say::DidNotAnswer(name) => write!(o, "{name} n’a pas répondu. Réessaie."),
        Say::RefusedPassphrase(name) => write!(o, "{name} a refusé la phrase secrète."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Une phrase secrète compte de ")?;
            num(o, f, min)?;
            o.write_str(" à ")?;
            num(o, f, max)?;
            o.write_str(" caractères simples.")
        }
    }
}
