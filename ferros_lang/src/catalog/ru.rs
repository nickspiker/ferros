/// The Russian plural form for `n`: one (1, 21, 31 ...), few (2-4, 22-24 ...), many (0, 5-20, 25-30 ...); 11 to 14 are always many.
fn form(n: u64, one: &'static str, few: &'static str, many: &'static str) -> &'static str {
    let (d, h) = (n % 10, n % 100);
    if d == 1 && h != 11 {
        one
    } else if (2..=4).contains(&d) && !(12..=14).contains(&h) {
        few
    } else {
        many
    }
}

pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "высота {up}°, азимут {round}°, {cn0} dB-Hz{}", if used { ", используется" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("сообщений от чипа: ")?;
            num(o, f, messages)?;
            o.write_str(", видов: ")?;
            num(o, f, kinds)?;
            o.write_str("; спутники появятся с первым местоположением")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, летнее время"),
        Say::HeardMcc(mcc) => write!(o, "услышан: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "услышан: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(form(n, " касание до страницы «Разработчик»", " касания до страницы «Разработчик»", " касаний до страницы «Разработчик»"))
        }
        Say::Charging(pct) => write!(o, "{pct}  заряжается"),
        Say::OnBattery(pct) => write!(o, "{pct}  от батареи"),
        Say::Throttled(t) => write!(o, "{t}  замедлен"),
        Say::NotAskedYet(what) => write!(o, "{what} (ещё не спрошено)"),
        Say::UsingNow(what) => write!(o, "{what} (использует сейчас)"),
        Say::CouldNotStart(name) => write!(o, "Не удалось запустить {name}"),
        Say::Stopped(name) => write!(o, "Работа {name} остановлена"),
        Say::ByDeveloper(name) => write!(o, "от {name}"),
        Say::KeptForItself(size) => write!(o, "{size}, без него бесполезно"),
        Say::Fetching { name, got } => write!(o, "загрузка {name}: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "загрузка {name}: {got} из {total}"),
        Say::Signal(dbm) => write!(o, "Сигнал {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Подключаемся к сети {name}."),
        Say::PassphraseFor(name) => write!(o, "Пароль для сети {name}."),
        Say::OutOfReach(name) => write!(o, "Сеть {name} вне досягаемости."),
        Say::SecurityUnsupported(name) => write!(o, "Сети {name} нужна защита, к которой это устройство пока не умеет подключаться."),
        Say::DidNotAnswer(name) => write!(o, "Сеть {name} не ответила. Попробуй ещё раз."),
        Say::RefusedPassphrase(name) => write!(o, "Сеть {name} не приняла пароль."),
        Say::PassphraseLength { min, max } => {
            // After "до" the genitive: singular for 1, 21, 31 ... (not 11), plural otherwise.
            o.write_str("Пароль: от ")?;
            num(o, f, min)?;
            o.write_str(" до ")?;
            num(o, f, max)?;
            o.write_str(if max % 10 == 1 && max % 100 != 11 { " обычного символа." } else { " обычных символов." })
        }
    }
}
