pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}\u{b0} teitei, {round}\u{b0} ahunga, {cn0} dB-Hz{}", if used { ", i te tūnga" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("ngā karere mai i te maramara: ")?;
            num(o, f, messages)?;
            o.write_str(", ngā momo: ")?;
            num(o, f, kinds)?;
            o.write_str("; ka puta ngā amiorangi i tōna tūnga tuatahi")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, wā whakaraumati"),
        Say::HeardMcc(mcc) => write!(o, "i rangona: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "i rangona: MCC {mcc}, {country}"),
        // One tap left takes the singular article; more take "e … ngā".
        Say::TapsToDeveloper(n) => {
            if n == 1 {
                num(o, f, n)?;
                o.write_str(" anō te pāwhiri ki Kaiwhakawhanake")
            } else {
                o.write_str("e ")?;
                num(o, f, n)?;
                o.write_str(" anō ngā pāwhiri ki Kaiwhakawhanake")
            }
        }
        Say::Charging(pct) => write!(o, "{pct}  e whakakī ana"),
        Say::OnBattery(pct) => write!(o, "{pct}  i te pūhiko"),
        Say::Throttled(t) => write!(o, "{t}  kua whakapōturihia"),
        Say::NotAskedYet(what) => write!(o, "{what} (kāore anō kia pātaitia)"),
        Say::UsingNow(what) => write!(o, "{what} (e whakamahi ana ināianei)"),
        Say::CouldNotStart(name) => write!(o, "Kāore i taea e {name} te tīmata"),
        Say::Stopped(name) => write!(o, "I tū a {name}"),
        Say::Signal(dbm) => write!(o, "Tohu {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "E hono ana ki {name}."),
        Say::PassphraseFor(name) => write!(o, "Te kupuhipa mō {name}."),
        Say::OutOfReach(name) => write!(o, "Kei tawhiti rawa a {name}."),
        Say::SecurityUnsupported(name) => write!(o, "Me whai a {name} i tētahi momo haumaru kāore anō e taea e tēnei pūrere te hono."),
        Say::DidNotAnswer(name) => write!(o, "Kāore a {name} i whakautu. Ngana anō."),
        Say::RefusedPassphrase(name) => write!(o, "I whakakāhore a {name} i te kupuhipa."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Ko te roa o te kupuhipa, ")?;
            num(o, f, min)?;
            o.write_str(" ki te ")?;
            num(o, f, max)?;
            o.write_str(" ngā pū māmā.")
        }
    }
}
