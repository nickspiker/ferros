pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° de elevação, {round}° de azimute, {cn0} dB-Hz{}", if used { ", em uso" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("mensagens do chip: ")?;
            num(o, f, messages)?;
            o.write_str(", tipos: ")?;
            num(o, f, kinds)?;
            o.write_str("; os satélites chegam com a primeira posição")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, horário de verão"),
        Say::HeardMcc(mcc) => write!(o, "recebido: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "recebido: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " toque para Desenvolvedor" } else { " toques para Desenvolvedor" })
        }
        Say::Charging(pct) => write!(o, "{pct}  carregando"),
        Say::OnBattery(pct) => write!(o, "{pct}  na bateria"),
        Say::Throttled(t) => write!(o, "{t}  limitado"),
        Say::NotAskedYet(what) => write!(o, "{what} (ainda não perguntado)"),
        Say::UsingNow(what) => write!(o, "{what} (usando agora)"),
        Say::CouldNotStart(name) => write!(o, "{name} não pôde iniciar"),
        Say::Stopped(name) => write!(o, "{name} parou"),
        Say::ByDeveloper(name) => write!(o, "de {name}"),
        Say::Signal(dbm) => write!(o, "Sinal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Conectando a {name}."),
        Say::PassphraseFor(name) => write!(o, "A senha de {name}."),
        Say::OutOfReach(name) => write!(o, "{name} está fora de alcance."),
        Say::SecurityUnsupported(name) => write!(o, "{name} usa um tipo de segurança com que este dispositivo ainda não consegue se conectar."),
        Say::DidNotAnswer(name) => write!(o, "{name} não respondeu. Tente de novo."),
        Say::RefusedPassphrase(name) => write!(o, "{name} recusou a senha."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Uma senha tem de ")?;
            num(o, f, min)?;
            o.write_str(" a ")?;
            num(o, f, max)?;
            o.write_str(" caracteres simples.")
        }
    }
}
