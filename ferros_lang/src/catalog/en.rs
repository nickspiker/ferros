pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}\u{b0} up, {round}\u{b0} round, {cn0} dB-Hz{}", if used { ", in the fix" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("messages from the chip: ")?;
            num(o, f, messages)?;
            o.write_str(", kinds: ")?;
            num(o, f, kinds)?;
            o.write_str("; satellites come with its first fix")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, daylight time"),
        Say::HeardMcc(mcc) => write!(o, "heard: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "heard: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " tap to Developer" } else { " taps to Developer" })
        }
        Say::Charging(pct) => write!(o, "{pct}  charging"),
        Say::OnBattery(pct) => write!(o, "{pct}  on battery"),
        Say::ChargeCapAt { mv, share } => write!(o, "{mv}, about {share}"),
        Say::ChargeCapDefault(mv) => write!(o, "{mv} is the default: most of the charge for far less wear."),
        Say::ApproveChargeCap(mv) => write!(o, "Approve: charge to {mv}."),
        Say::ChargeCapCycles { share, mv } => write!(o, "about {share} of the charge cycles at {mv}"),
        Say::Throttled(t) => write!(o, "{t}  throttled"),
        Say::NotAskedYet(what) => write!(o, "{what} (not asked yet)"),
        Say::UsingNow(what) => write!(o, "{what} (using now)"),
        Say::CouldNotStart(name) => write!(o, "{name} could not start"),
        Say::Stopped(name) => write!(o, "{name} stopped"),
        Say::ByDeveloper(name) => write!(o, "by {name}"),
        Say::KeptForItself(size) => write!(o, "{size}, of no use without it"),
        Say::Fetching { name, got } => write!(o, "fetching {name}: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "fetching {name}: {got} of {total}"),
        Say::Signal(dbm) => write!(o, "Signal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Joining {name}."),
        Say::PassphraseFor(name) => write!(o, "The passphrase for {name}."),
        Say::OutOfReach(name) => write!(o, "{name} is out of reach."),
        Say::SecurityUnsupported(name) => write!(o, "{name} needs a kind of security this device cannot join yet."),
        Say::DidNotAnswer(name) => write!(o, "{name} did not answer. Try again."),
        Say::RefusedPassphrase(name) => write!(o, "{name} refused the passphrase."),
        Say::TypeOnKeyboard(name) => write!(o, "Type the passphrase for {name} on the keyboard."),
        Say::JoinedNet(name) => write!(o, "Joined {name}."),
        Say::Forgotten(name) => write!(o, "{name} forgotten."),
        Say::OpenIn(name) => write!(o, "open in {name}"),
        Say::PassphraseLength { min, max } => {
            o.write_str("A passphrase is ")?;
            num(o, f, min)?;
            o.write_str(" to ")?;
            num(o, f, max)?;
            o.write_str(" plain characters.")
        }
        Say::UnderFullScale(n) => {
            num(o, f, n)?;
            o.write_str(" dB under full scale")?;
            Ok(())
        }
        Say::AmpState { side, pup, pll, errors } => {
            o.write_str(side)?;
            o.write_str(": PUP_DONE ")?;
            num(o, f, pup)?;
            o.write_str(", PLL lock ")?;
            num(o, f, pll)?;
            o.write_str(", errors ")?;
            o.write_str(errors)?;
            Ok(())
        }
        Say::MicLevel { mic, under } => {
            o.write_str("microphone ")?;
            num(o, f, mic)?;
            o.write_str(": ")?;
            num(o, f, under)?;
            o.write_str(" dB under full scale")?;
            Ok(())
        }
        Say::MicQuiet(mic) => {
            o.write_str("microphone ")?;
            num(o, f, mic)?;
            o.write_str(": silent")?;
            Ok(())
        }
        Say::MicName(n) => {
            o.write_str("microphone ")?;
            num(o, f, n)?;
            Ok(())
        }
        Say::PlayingBack(d) => {
            o.write_str("recorded, its peak ")?;
            num(o, f, d)?;
            o.write_str(" dB under full scale: playing it back")?;
            Ok(())
        }
        Say::RomWaveform(n) => {
            o.write_str("ROM waveform ")?;
            num(o, f, n)?;
            Ok(())
        }
    }
}
