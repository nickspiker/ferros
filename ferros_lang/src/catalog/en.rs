pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}\u{b0} up, {round}\u{b0} round, {cn0} dB-Hz{}", if used { ", in the fix" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("messages from the chip: ")?;
            num(o, f, messages)?;
            o.write_str(", kinds: ")?;
            num(o, f, kinds)?;
            o.write_str("; satellites come with its first fix")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, daylight time"),
        Say::HeardMcc(mcc) => write!(o, "heard: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "heard: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " tap to Developer" } else { " taps to Developer" })
        }
        Say::Charging(pct) => write!(o, "{pct}  charging"),
        Say::OnBattery(pct) => write!(o, "{pct}  on battery"),
        Say::Throttled(t) => write!(o, "{t}  throttled"),
        Say::NotAskedYet(what) => write!(o, "{what} (not asked yet)"),
        Say::UsingNow(what) => write!(o, "{what} (using now)"),
        Say::CouldNotStart(name) => write!(o, "{name} could not start"),
        Say::Stopped(name) => write!(o, "{name} stopped"),
        Say::Signal(dbm) => write!(o, "Signal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Joining {name}."),
        Say::PassphraseFor(name) => write!(o, "The passphrase for {name}."),
        Say::OutOfReach(name) => write!(o, "{name} is out of reach."),
        Say::SecurityUnsupported(name) => write!(o, "{name} needs a kind of security this device cannot join yet."),
        Say::DidNotAnswer(name) => write!(o, "{name} did not answer. Try again."),
        Say::RefusedPassphrase(name) => write!(o, "{name} refused the passphrase."),
        Say::PassphraseLength { min, max } => {
            o.write_str("A passphrase is ")?;
            num(o, f, min)?;
            o.write_str(" to ")?;
            num(o, f, max)?;
            o.write_str(" plain characters.")
        }
    }
}
