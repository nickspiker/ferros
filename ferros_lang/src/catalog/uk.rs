/// The Ukrainian plural form for `n`: one (1, 21, 31 ...), few (2-4, 22-24 ...), many (0, 5-20, 25-30 ...); 11 to 14 are always many.
fn form(n: u64, one: &'static str, few: &'static str, many: &'static str) -> &'static str {
    let (d, h) = (n % 10, n % 100);
    if d == 1 && h != 11 {
        one
    } else if (2..=4).contains(&d) && !(12..=14).contains(&h) {
        few
    } else {
        many
    }
}

pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "висота {up}°, азимут {round}°, {cn0} dB-Hz{}", if used { ", використовується" } else { "" }),
        Say::DaylightTime(utc) => write!(o, "{utc}, літній час"),
        Say::HeardMcc(mcc) => write!(o, "почуто: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "почуто: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(form(n, " дотик до сторінки «Розробник»", " дотики до сторінки «Розробник»", " дотиків до сторінки «Розробник»"))
        }
        Say::Charging(pct) => write!(o, "{pct}  заряджається"),
        Say::OnBattery(pct) => write!(o, "{pct}  від батареї"),
        Say::Throttled(t) => write!(o, "{t}  пригальмовано"),
        Say::NotAskedYet(what) => write!(o, "{what} (ще не запитано)"),
        Say::Signal(dbm) => write!(o, "Сигнал {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Підключаюся до мережі {name}."),
        Say::PassphraseFor(name) => write!(o, "Пароль для мережі {name}."),
        Say::OutOfReach(name) => write!(o, "Мережа {name} поза досяжністю."),
        Say::SecurityUnsupported(name) => write!(o, "Мережі {name} потрібен вид захисту, до якого цей пристрій ще не вміє підключатися."),
        Say::DidNotAnswer(name) => write!(o, "Мережа {name} не відповіла. Спробуй ще раз."),
        Say::RefusedPassphrase(name) => write!(o, "Мережа {name} не прийняла пароль."),
        Say::PassphraseLength { min, max } => {
            // After "до" the genitive: singular for 1, 21, 31 ... (not 11), plural otherwise.
            o.write_str("Пароль: від ")?;
            num(o, f, min)?;
            o.write_str(" до ")?;
            num(o, f, max)?;
            o.write_str(if max % 10 == 1 && max % 100 != 11 { " звичайного символу." } else { " звичайних символів." })
        }
    }
}
