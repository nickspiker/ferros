pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}\u{b0} juu, {round}\u{b0} mzunguko, {cn0} dB-Hz{}", if used { ", inatumika kwa mahali" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("jumbe kutoka kwa chipu: ")?;
            num(o, f, messages)?;
            o.write_str(", aina: ")?;
            num(o, f, kinds)?;
            o.write_str("; setilaiti huja na mahali pake pa kwanza")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, saa za kuokoa mchana"),
        Say::HeardMcc(mcc) => write!(o, "imesikika: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "imesikika: MCC {mcc}, {country}"),
        // The noun's class changes with the count (mguso, miguso); the number follows the noun.
        Say::TapsToDeveloper(n) => {
            o.write_str(if n == 1 { "mguso " } else { "miguso " })?;
            num(o, f, n)?;
            o.write_str(" zaidi hadi Msanidi")
        }
        Say::Charging(pct) => write!(o, "{pct}  inachaji"),
        Say::OnBattery(pct) => write!(o, "{pct}  kwa betri"),
        Say::Throttled(t) => write!(o, "{t}  imepunguzwa kasi"),
        Say::NotAskedYet(what) => write!(o, "{what} (bado haijaulizwa)"),
        Say::UsingNow(what) => write!(o, "{what} (inatumia sasa)"),
        Say::CouldNotStart(name) => write!(o, "{name} haikuweza kuanza"),
        Say::Stopped(name) => write!(o, "{name} imesimama"),
        Say::ByDeveloper(name) => write!(o, "na {name}"),
        Say::Fetching { name, got } => write!(o, "inapakua {name}: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "inapakua {name}: {got} kati ya {total}"),
        Say::Signal(dbm) => write!(o, "Mawimbi {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Inajiunga na {name}."),
        Say::PassphraseFor(name) => write!(o, "Nywila ya {name}."),
        Say::OutOfReach(name) => write!(o, "{name} iko nje ya ufikiaji."),
        Say::SecurityUnsupported(name) => write!(o, "{name} inahitaji aina ya usalama ambayo kifaa hiki bado hakiwezi kujiunga nayo."),
        Say::DidNotAnswer(name) => write!(o, "{name} haikujibu. Jaribu tena."),
        Say::RefusedPassphrase(name) => write!(o, "{name} imekataa nywila."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Nywila ina herufi za kawaida ")?;
            num(o, f, min)?;
            o.write_str(" hadi ")?;
            num(o, f, max)?;
            o.write_str(".")
        }
    }
}
