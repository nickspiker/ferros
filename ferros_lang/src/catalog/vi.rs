pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "cao {up}°, hướng {round}°, {cn0} dB-Hz{}", if used { ", dùng để định vị" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("tin nhắn từ chip: ")?;
            num(o, f, messages)?;
            o.write_str(", loại: ")?;
            num(o, f, kinds)?;
            o.write_str("; vệ tinh hiện ra khi có vị trí đầu tiên")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, giờ mùa hè"),
        Say::HeardMcc(mcc) => write!(o, "nghe thấy: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "nghe thấy: MCC {mcc}, {country}"),
        // Vietnamese does not mark the plural on the noun; one form serves every count.
        Say::TapsToDeveloper(n) => {
            o.write_str("còn ")?;
            num(o, f, n)?;
            o.write_str(" lần chạm để tới Nhà phát triển")
        }
        Say::Charging(pct) => write!(o, "{pct}  đang sạc"),
        Say::OnBattery(pct) => write!(o, "{pct}  dùng pin"),
        Say::Throttled(t) => write!(o, "{t}  bị hạ xung"),
        Say::NotAskedYet(what) => write!(o, "{what} (chưa hỏi)"),
        Say::UsingNow(what) => write!(o, "{what} (đang dùng)"),
        Say::CouldNotStart(name) => write!(o, "{name} không thể khởi động"),
        Say::Stopped(name) => write!(o, "{name} đã dừng"),
        Say::Signal(dbm) => write!(o, "Tín hiệu {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Đang kết nối {name}."),
        Say::PassphraseFor(name) => write!(o, "Mật khẩu của {name}."),
        Say::OutOfReach(name) => write!(o, "{name} ở ngoài tầm."),
        Say::SecurityUnsupported(name) => write!(o, "{name} cần một kiểu bảo mật mà thiết bị này chưa kết nối được."),
        Say::DidNotAnswer(name) => write!(o, "{name} không trả lời. Thử lại."),
        Say::RefusedPassphrase(name) => write!(o, "{name} từ chối mật khẩu."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Mật khẩu dài từ ")?;
            num(o, f, min)?;
            o.write_str(" đến ")?;
            num(o, f, max)?;
            o.write_str(" ký tự cơ bản.")
        }
    }
}
