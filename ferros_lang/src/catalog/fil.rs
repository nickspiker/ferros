pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}\u{b0} pataas, {round}\u{b0} paikot, {cn0} dB-Hz{}", if used { ", gamit sa lokasyon" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("mga mensahe mula sa chip: ")?;
            num(o, f, messages)?;
            o.write_str(", mga uri: ")?;
            num(o, f, kinds)?;
            o.write_str("; lalabas ang mga satellite sa unang lokasyon nito")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, daylight saving time"),
        Say::HeardMcc(mcc) => write!(o, "narinig: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "narinig: MCC {mcc}, {country}"),
        // Filipino does not inflect the noun for number; the count stands before it as it does in English.
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(" pindot pa papunta sa Developer")
        }
        Say::Charging(pct) => write!(o, "{pct}  nagcha-charge"),
        Say::OnBattery(pct) => write!(o, "{pct}  sa baterya"),
        Say::Throttled(t) => write!(o, "{t}  pinabagal"),
        Say::NotAskedYet(what) => write!(o, "{what} (hindi pa naitatanong)"),
        Say::UsingNow(what) => write!(o, "{what} (ginagamit ngayon)"),
        Say::CouldNotStart(name) => write!(o, "Hindi makapagsimula ang {name}"),
        Say::Stopped(name) => write!(o, "Huminto ang {name}"),
        Say::ByDeveloper(name) => write!(o, "gawa ni {name}"),
        Say::Signal(dbm) => write!(o, "Signal {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Sumasali sa {name}."),
        Say::PassphraseFor(name) => write!(o, "Ang passphrase para sa {name}."),
        Say::OutOfReach(name) => write!(o, "Hindi maabot ang {name}."),
        Say::SecurityUnsupported(name) => write!(o, "Kailangan ng {name} ng uri ng seguridad na hindi pa kayang salihan ng device na ito."),
        Say::DidNotAnswer(name) => write!(o, "Hindi sumagot ang {name}. Subukan ulit."),
        Say::RefusedPassphrase(name) => write!(o, "Tinanggihan ng {name} ang passphrase."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Ang passphrase ay ")?;
            num(o, f, min)?;
            o.write_str(" hanggang ")?;
            num(o, f, max)?;
            o.write_str(" na payak na character.")
        }
    }
}
