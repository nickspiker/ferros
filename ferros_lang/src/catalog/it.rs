pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° di elevazione, {round}° di azimut, {cn0} dB-Hz{}", if used { ", in uso" } else { "" }),
        Say::ChipHeard { messages, kinds } => {
            o.write_str("messaggi dal chip: ")?;
            num(o, f, messages)?;
            o.write_str(", tipi: ")?;
            num(o, f, kinds)?;
            o.write_str("; i satelliti arrivano con la prima posizione")
        }
        Say::DaylightTime(utc) => write!(o, "{utc}, ora legale"),
        Say::HeardMcc(mcc) => write!(o, "ricevuto: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "ricevuto: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " tocco per Sviluppatore" } else { " tocchi per Sviluppatore" })
        }
        Say::Charging(pct) => write!(o, "{pct}  in carica"),
        Say::OnBattery(pct) => write!(o, "{pct}  a batteria"),
        Say::ChargeCapAt { mv, share } => write!(o, "{mv}, circa {share}"),
        Say::ChargeCapDefault(mv) => write!(o, "{mv} è il valore predefinito: quasi tutta la carica con molta meno usura."),
        Say::ApproveChargeCap(mv) => write!(o, "Approva: carica fino a {mv}."),
        Say::ChargeCapCycles { share, mv } => write!(o, "circa {share} dei cicli di carica a {mv}"),
        Say::Throttled(t) => write!(o, "{t}  rallentato"),
        Say::NotAskedYet(what) => write!(o, "{what} (non ancora chiesto)"),
        Say::UsingNow(what) => write!(o, "{what} (in uso ora)"),
        Say::CouldNotStart(name) => write!(o, "{name} non è riuscito ad avviarsi"),
        Say::Stopped(name) => write!(o, "{name} si è fermato"),
        Say::ByDeveloper(name) => write!(o, "di {name}"),
        Say::KeptForItself(size) => write!(o, "{size}, inutile senza di lui"),
        Say::Fetching { name, got } => write!(o, "scaricamento di {name}: {got}"),
        Say::FetchingOf { name, got, total } => write!(o, "scaricamento di {name}: {got} di {total}"),
        Say::Signal(dbm) => write!(o, "Segnale {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Connessione a {name}."),
        Say::PassphraseFor(name) => write!(o, "La password di {name}."),
        Say::OutOfReach(name) => write!(o, "{name} è fuori portata."),
        Say::SecurityUnsupported(name) => write!(o, "{name} usa un tipo di sicurezza a cui questo dispositivo non sa ancora connettersi."),
        Say::DidNotAnswer(name) => write!(o, "{name} non ha risposto. Riprova."),
        Say::RefusedPassphrase(name) => write!(o, "{name} ha rifiutato la password."),
        Say::TypeOnKeyboard(name) => write!(o, "Scrivi la password di {name} sulla tastiera."),
        Say::JoinedNet(name) => write!(o, "Connesso a {name}."),
        Say::Forgotten(name) => write!(o, "{name} dimenticata."),
        Say::OpenIn(name) => write!(o, "apri in {name}"),
        Say::PassphraseLength { min, max } => {
            o.write_str("Una password va da ")?;
            num(o, f, min)?;
            o.write_str(" a ")?;
            num(o, f, max)?;
            o.write_str(" caratteri semplici.")
        }
        Say::UnderFullScale(n) => {
            num(o, f, n)?;
            o.write_str(" dB sotto il fondo scala")?;
            Ok(())
        }
        Say::AmpState { side, pup, pll, errors } => {
            o.write_str(side)?;
            o.write_str(": PUP_DONE ")?;
            num(o, f, pup)?;
            o.write_str(", PLL agganciato ")?;
            num(o, f, pll)?;
            o.write_str(", errori ")?;
            o.write_str(errors)?;
            Ok(())
        }
        Say::MicLevel { mic, under } => {
            o.write_str("microfono ")?;
            num(o, f, mic)?;
            o.write_str(": ")?;
            num(o, f, under)?;
            o.write_str(" dB sotto il fondo scala")?;
            Ok(())
        }
        Say::MicQuiet(mic) => {
            o.write_str("microfono ")?;
            num(o, f, mic)?;
            o.write_str(": silenzio")?;
            Ok(())
        }
        Say::MicName(n) => {
            o.write_str("microfono ")?;
            num(o, f, n)?;
            Ok(())
        }
        Say::PlayingBack(d) => {
            o.write_str("registrato, picco a ")?;
            num(o, f, d)?;
            o.write_str(" dB sotto il fondo scala: in riproduzione")?;
            Ok(())
        }
        Say::RomWaveform(n) => {
            o.write_str("forma d’onda ROM ")?;
            num(o, f, n)?;
            Ok(())
        }
    }
}
