pub fn say(m: Say, f: tatau::Fmt, o: &mut dyn Write) -> fmt::Result {
    match m {
        Say::SatPlace { up, round, cn0, used } => write!(o, "{up}° di elevazione, {round}° di azimut, {cn0} dB-Hz{}", if used { ", in uso" } else { "" }),
        Say::DaylightTime(utc) => write!(o, "{utc}, ora legale"),
        Say::HeardMcc(mcc) => write!(o, "ricevuto: MCC {mcc}"),
        Say::HeardMccIn { mcc, country } => write!(o, "ricevuto: MCC {mcc}, {country}"),
        Say::TapsToDeveloper(n) => {
            num(o, f, n)?;
            o.write_str(if n == 1 { " tocco per Sviluppatore" } else { " tocchi per Sviluppatore" })
        }
        Say::Charging(pct) => write!(o, "{pct}  in carica"),
        Say::OnBattery(pct) => write!(o, "{pct}  a batteria"),
        Say::Throttled(t) => write!(o, "{t}  rallentato"),
        Say::NotAskedYet(what) => write!(o, "{what} (non ancora chiesto)"),
        Say::UsingNow(what) => write!(o, "{what} (in uso ora)"),
        Say::CouldNotStart(name) => write!(o, "{name} non è riuscito ad avviarsi"),
        Say::Signal(dbm) => write!(o, "Segnale {dbm} dBm"),
        Say::JoiningNet(name) => write!(o, "Connessione a {name}."),
        Say::PassphraseFor(name) => write!(o, "La password di {name}."),
        Say::OutOfReach(name) => write!(o, "{name} è fuori portata."),
        Say::SecurityUnsupported(name) => write!(o, "{name} usa un tipo di sicurezza a cui questo dispositivo non sa ancora connettersi."),
        Say::DidNotAnswer(name) => write!(o, "{name} non ha risposto. Riprova."),
        Say::RefusedPassphrase(name) => write!(o, "{name} ha rifiutato la password."),
        Say::PassphraseLength { min, max } => {
            o.write_str("Una password va da ")?;
            num(o, f, min)?;
            o.write_str(" a ")?;
            num(o, f, max)?;
            o.write_str(" caratteri semplici.")
        }
    }
}
