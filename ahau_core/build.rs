//! The attest screen's encoder table, generated: vsf's `x` Huffman code for every character the honeycomb keyboard can type (`honeycomb::typeable`), read from the frozen codebook ihi's identity seed is pinned to (vsf 0.6.42's `huffman_codes.bin`, the sibling vsf checkout carries the same file). A key added to the keyboard gets its exact code here; a key whose character is not its own NFC form, or is a combining mark, fails the build, because vsf normalizes before it encodes and this encoder does not: the seed would name someone else.
use std::collections::BTreeMap;
use unicode_normalization::char::canonical_combining_class;
use unicode_normalization::UnicodeNormalization;

/// BLAKE3 of the frozen codebook (ihi's encoder lane). Any other file names other identities.
const CODEBOOK_BLAKE3: &str = "523769a934a407aa87d9ddef37ad186c546e205cb1280b0e9300d6e98c6dad0e";
const CODEBOOK: &str = "../../vsf/huffman_codes.bin";

fn main() {
    println!("cargo:rerun-if-changed={CODEBOOK}");
    println!("cargo:rerun-if-changed=../honeycomb/src/lib.rs");
    let data = std::fs::read(CODEBOOK).unwrap_or_else(|e| panic!("{CODEBOOK}: {e}"));
    assert_eq!(blake3::hash(&data).to_hex().as_str(), CODEBOOK_BLAKE3, "{CODEBOOK} is not the frozen codebook");
    assert_eq!(&data[..4], b"HUFF", "{CODEBOOK}: not a codebook");
    let count = u32::from_le_bytes(data[8..12].try_into().unwrap()) as usize;
    let mut book = BTreeMap::new();
    for i in 0..count {
        let at = 12 + i * 8;
        let cp = u32::from_le_bytes(data[at..at + 4].try_into().unwrap());
        let packed = u32::from_le_bytes(data[at + 4..at + 8].try_into().unwrap());
        if let Some(c) = char::from_u32(cp) {
            book.insert(c, (packed & 0x00FF_FFFF, ((packed >> 24) & 0x1F) as u8));
        }
    }
    let mut out = BTreeMap::new();
    for c in honeycomb::typeable() {
        let s: String = [c].iter().collect();
        assert_eq!(s.nfc().collect::<String>(), s, "the keyboard types {c:?}, which is not its own NFC form");
        assert_eq!(canonical_combining_class(c), 0, "the keyboard types {c:?}, a combining mark");
        let code = *book.get(&c).unwrap_or_else(|| panic!("the codebook has no code for {c:?}"));
        assert!(code.1 > 0, "a zero-length code for {c:?}");
        out.insert(c, code);
    }
    let mut src = String::from("/// Generated by build.rs from the frozen codebook: (character, code bits, length) for every character the honeycomb keyboard can type, sorted.\n");
    src.push_str(&format!("pub const CODES: [(char, u32, u8); {}] = [\n", out.len()));
    for (c, (bits, len)) in &out {
        src.push_str(&format!("    ({c:?}, {bits:#b}, {len}),\n"));
    }
    src.push_str("];\n");
    std::fs::write(std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("codes.rs"), src).unwrap();
}
